conn = sqlite3.connect("gis_services.db")
conn.execute("PRAGMA busy_timeout=10000")
cur = conn.cursor()
cols = [r[1] for r in cur.execute("PRAGMA table_info(master)")]

def fill_defaults(values):
    for k in ("caching_allowed", "rate_limit", "query_limit", "download_limit",
              "pagination", "batch_query"):
        values.setdefault(k, "未知")

sid_num = 1218
inserted, skipped = [], []
for row in ROWS + MANUAL_WEAK:
    sid = f"DS-{sid_num}"
    sid_num += 1
    platform = row["platform"]
    root = ("https://" + row["host"]).lower()
    dup = cur.execute(
        "SELECT service_id FROM master WHERE LOWER(service_url) LIKE ? OR LOWER(official_url) LIKE ? "
        "OR LOWER(service_name)=LOWER(?)",
        (root + "%", root + "%", row["name"]),
    ).fetchone()
    if dup:
        skipped.append((sid, row["name"], dup[0]))
        continue
    strong = platform != "page200"
    values = {c: None for c in cols}
    values.update({
        "service_id": sid,
        "service_name": row["name"][:120],
        "country": row["country"],
        "region": None,
        "provider": row["name"][:120],
        "category": row["cat"],
        "service_type": row["service_type"],
        "protocol": row["protocol"],
        "official_url": row["link"],
        "service_url": row["api"],
        "docs_url": row["link"],
        "data_description": (row["desc"] or "开放地理空间数据门户")[:500],
        "spatial_coverage": row["country"] if row["country"] != "全球" else "全球",
        "temporal_coverage": "持续更新",
        "crs": "EPSG:4326",
        "format": row["fmt"],
        "auth": "无(公开接口)" if strong else "无",
        "api_key_required": "否",
        "registration_required": "否",
        "free": "是",
        "commercial_use": "是(以站点许可为准)",
        "redistribution": "是(以站点许可为准)",
        "need_no_reg": "是",
        "need_no_key": "是",
        "is_free": "是",
        "support_api": "是" if strong else "部分",
        "support_spatial_query": "是",
        "support_temporal_query": "否",
        "support_download": "是",
        "support_geojson": "部分",
        "support_json": "是" if strong else "否",
        "is_vector": row["is_vector"],
        "is_raster": row["is_raster"],
        "is_realtime": "否",
        "global_coverage": "是" if row["country"] == "全球" else "否",
        "region_coverage": "否" if row["country"] == "全球" else "是",
        "status": "已验证",
        "verify_method": "protocol-probe:strong" if strong else "protocol-probe:weak",
        "last_verified": TODAY,
    })
    fill_defaults(values)
    placeholders = ",".join("?" for _ in cols)
    cur.execute(f"INSERT INTO master ({','.join(cols)}) VALUES ({placeholders})",
                [values[c] for c in cols])
    inserted.append(sid)

conn.commit()
n = cur.execute("select count(*) from master").fetchone()[0]
nv = cur.execute("select count(*) from master where status='已验证'").fetchone()[0]
print(f"插入 {len(inserted)} 条 -> master 总数 {n}，已验证 {nv}")
if skipped:
    print(f"跳过(查重命中) {len(skipped)} 条：")
    for s in skipped[:20]:
        print("  ", s)
conn.close()
