conn = sqlite3.connect("gis_services.db")
conn.execute("PRAGMA busy_timeout=10000")
cur = conn.cursor()
cols = [r[1] for r in cur.execute("PRAGMA table_info(master)")]

inserted, skipped = [], []
for row in NEW_ROWS:
    dup_url = cur.execute(
        "SELECT service_id FROM master WHERE service_url LIKE ? OR official_url LIKE ?",
        (row["service_url"].split("?")[0] + "%", row["official_url"].split("?")[0] + "%"),
    ).fetchone()
    dup_name = cur.execute(
        "SELECT service_id FROM master WHERE LOWER(service_name)=LOWER(?)",
        (row["service_name"],),
    ).fetchone()
    if dup_url or dup_name:
        skipped.append((row["service_id"], row["service_name"], dup_url or dup_name))
        continue
    values = {c: None for c in cols}
    for k, v in row.items():
        if k in cols:
            values[k] = v
    for k in ("caching_allowed", "rate_limit", "query_limit", "download_limit",
              "pagination", "batch_query"):
        values.setdefault(k, "未知")
    placeholders = ",".join("?" for _ in cols)
    cur.execute(f"INSERT INTO master ({','.join(cols)}) VALUES ({placeholders})",
                [values[c] for c in cols])
    inserted.append(row["service_id"])

conn.commit()
n = cur.execute("select count(*) from master").fetchone()[0]
nv = cur.execute("select count(*) from master where status='已验证'").fetchone()[0]
print(f"插入 {len(inserted)} 条 -> master 总数 {n}，已验证 {nv}")
if skipped:
    print("跳过(查重命中):")
    for s in skipped:
        print("  ", s)
